/** Generated agent-desktop configuration: monitor rule, panic bind, inline snippets, and hash. */
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test, type TestContext } from 'node:test'
import {
  DESKTOP_CONFIG_MARKER, hashDesktopConfig, renderConfig, validSize, writeDesktopConfig,
} from '../src/desktop/config.ts'
import { ErrorCode, HyprscopeError } from '../src/errors.ts'
import { BIND_DESCRIPTION } from '../src/lease/bind.ts'

/** Panic command with spaces and quotes, so quoting is exercised rather than assumed. */
const PANIC_COMMAND = `/opt/no de/node '/opt/hyprscope.ts' control panic --source shortcut`

/**
 * Create a disposable configuration directory below TMPDIR.
 * @param t Test context that removes the tree afterwards.
 * @returns Absolute directory path.
 */
function tempConfigDir(t: TestContext): string {
  const base = process.env.TMPDIR ?? tmpdir()
  mkdirSync(base, { recursive: true })
  const dir = mkdtempSync(join(base, 'hyprscope-desktop-'))
  t.after(() => { rmSync(dir, { recursive: true, force: true }) })
  return dir
}

/**
 * Write one agent snippet into a configuration directory.
 * @param dir Configuration directory.
 * @param name Snippet basename.
 * @param content Lua source.
 */
function writeSnippet(dir: string, name: string, content: string): void {
  const agentDir = join(dir, 'hypr', 'agent')
  mkdirSync(agentDir, { recursive: true })
  writeFileSync(join(agentDir, name), content)
}

/**
 * Read the generated configuration.
 * @param dir Configuration directory.
 * @returns Lua source.
 */
function readConfig(dir: string): string {
  return readFileSync(join(dir, 'hypr', 'hyprland.lua'), 'utf8')
}

/**
 * Count non-overlapping occurrences of one literal in a string.
 * @param text Haystack.
 * @param needle Literal to count.
 * @returns Occurrence count.
 */
function count(text: string, needle: string): number {
  return text.split(needle).length - 1
}

/**
 * Assert that a thrown value is a coded USAGE failure.
 * @param error Thrown value.
 * @returns Always true, so assert.throws and assert.rejects accept it.
 */
function usageError(error: unknown): boolean {
  assert.ok(error instanceof HyprscopeError)
  assert.equal(error.code, ErrorCode.USAGE)
  return true
}

test('renderConfig starts with the marker and writes one preferred monitor rule', () => {
  const text = renderConfig({ panicCommand: PANIC_COMMAND })
  const lines = text.split('\n')
  assert.equal(lines[0], DESKTOP_CONFIG_MARKER + '; do not edit this file.')
  assert.equal(lines.includes('hl.monitor({ output = "", mode = "preferred", scale = 1 })'), true)
  assert.equal(count(text, 'hl.monitor('), 1)
  assert.ok(lines.some(line => line.startsWith('-- ') && line.includes('agent/*.lua')))
  assert.ok(text.includes('-- >>> agent snippets >>>'))
  assert.ok(text.includes('-- <<< agent snippets <<<'))
  assert.equal(renderConfig({ size: null, panicCommand: PANIC_COMMAND }), text)
})

test('renderConfig writes the requested size into the only monitor rule', () => {
  for (const size of ['1280x800', '800x600', '2560x1440']) {
    const text = renderConfig({ size, panicCommand: PANIC_COMMAND })
    assert.ok(text.includes('hl.monitor({ output = "", mode = "' + size + '", scale = 1 })'), size)
    assert.equal(count(text, 'hl.monitor('), 1, size)
  }
})

test('renderConfig writes exactly one panic bind with the command JSON-quoted', () => {
  const text = renderConfig({ panicCommand: PANIC_COMMAND })
  const bind = 'hl.bind("SUPER + ALT + Escape", hl.dsp.exec_cmd(' + JSON.stringify(PANIC_COMMAND)
    + '), { description = ' + JSON.stringify(BIND_DESCRIPTION) + ' })'
  assert.ok(text.includes(bind))
  assert.ok(text.includes('hyprscope failsafe: revoke desktop control'))
  assert.ok(!text.includes('"SUPER + ALT + ESC"'))
  assert.equal(count(text, 'hl.bind('), 1)
})

test('renderConfig escapes double quotes in the panic command', () => {
  const command = `/opt/node '/opt/it"s here/hyprscope.ts' control panic`
  const text = renderConfig({ panicCommand: command })
  assert.ok(text.includes('hl.dsp.exec_cmd(' + JSON.stringify(command) + ')'))
  assert.ok(!text.includes(command))
})

test('renderConfig adds no startup command, extra bind, or Lua indirection', () => {
  const text = renderConfig({ size: '1280x800', panicCommand: PANIC_COMMAND })
  for (const forbidden of ['autostart', 'exec-once', 'dofile', 'require']) {
    assert.ok(!text.includes(forbidden), forbidden)
  }
  assert.equal(count(text, 'hl.bind('), 1)
  assert.equal(count(text, 'hl.monitor('), 1)
})

test('writeDesktopConfig embeds agent snippets inline, sorted by basename', async (t) => {
  const dir = tempConfigDir(t)
  writeSnippet(dir, 'z.lua', 'hl.window_rule({ match = { class = "z" }, float = true })')
  writeSnippet(dir, 'a.lua', 'hl.window_rule({ match = { class = "a" }, float = true })')
  writeSnippet(dir, 'm.lua', 'hl.window_rule({ match = { class = "m" }, float = true })')
  writeSnippet(dir, 'notes.txt', 'not Lua')
  mkdirSync(join(dir, 'hypr', 'agent', 'nested.lua'), { recursive: true })
  const result = await writeDesktopConfig({ configDir: dir, size: '1280x800', panicCommand: PANIC_COMMAND })
  assert.equal(result.file, join(dir, 'hypr', 'hyprland.lua'))
  assert.deepEqual(result.snippets, ['a.lua', 'm.lua', 'z.lua'])
  const text = readConfig(dir)
  const begin = text.indexOf('-- >>> agent snippets >>>')
  const end = text.indexOf('-- <<< agent snippets <<<')
  assert.ok(begin >= 0)
  assert.ok(end > begin)
  for (const name of ['a.lua', 'm.lua', 'z.lua']) {
    const header = text.indexOf('-- agent/' + name + '\n')
    assert.ok(header > begin && header < end, name)
  }
  assert.ok(text.indexOf('-- agent/a.lua') < text.indexOf('-- agent/m.lua'))
  assert.ok(text.indexOf('-- agent/m.lua') < text.indexOf('-- agent/z.lua'))
  assert.ok(text.includes('hl.window_rule({ match = { class = "a" }, float = true })'))
  assert.ok(!text.includes('notes.txt'))
  assert.ok(!text.includes('nested.lua'))
  assert.ok(text.includes('mode = "1280x800"'))
  assert.ok(!text.includes('dofile'))
  assert.ok(!text.includes('require'))
})

test('writeDesktopConfig creates the agent directory with mode 0700', async (t) => {
  const dir = tempConfigDir(t)
  await writeDesktopConfig({ configDir: dir, panicCommand: PANIC_COMMAND })
  assert.equal(statSync(join(dir, 'hypr', 'agent')).mode & 0o777, 0o700)
})

test('hashDesktopConfig is stable across a rewrite', async (t) => {
  const dir = tempConfigDir(t)
  writeSnippet(dir, 'a.lua', 'hl.window_rule({ float = true })')
  const first = await writeDesktopConfig({ configDir: dir, panicCommand: PANIC_COMMAND })
  assert.match(first.hash, /^[0-9a-f]{64}$/)
  assert.equal(await hashDesktopConfig(dir), first.hash)
  const second = await writeDesktopConfig({ configDir: dir, panicCommand: PANIC_COMMAND })
  assert.deepEqual(second.snippets, ['a.lua'])
  assert.equal(second.hash, first.hash)
  assert.equal(await hashDesktopConfig(dir), first.hash)
})

test('hashDesktopConfig changes when a snippet is edited, added, or removed', async (t) => {
  const dir = tempConfigDir(t)
  writeSnippet(dir, 'a.lua', 'first version')
  const base = await writeDesktopConfig({ configDir: dir, panicCommand: PANIC_COMMAND })
  writeSnippet(dir, 'a.lua', 'second version')
  const edited = await hashDesktopConfig(dir)
  assert.notEqual(edited, base.hash)
  writeSnippet(dir, 'b.lua', 'added snippet')
  const added = await hashDesktopConfig(dir)
  assert.notEqual(added, edited)
  rmSync(join(dir, 'hypr', 'agent', 'b.lua'))
  assert.equal(await hashDesktopConfig(dir), edited)
  rmSync(join(dir, 'hypr', 'agent', 'a.lua'))
  assert.notEqual(await hashDesktopConfig(dir), edited)
})

test('hashDesktopConfig hashes the empty string when the file is missing', async (t) => {
  const dir = join(tempConfigDir(t), 'absent')
  const first = await hashDesktopConfig(dir)
  assert.equal(first, await hashDesktopConfig(dir))
  assert.equal(first, createHash('sha256').update('').digest('hex'))
  writeSnippet(dir, 'a.lua', 'snippet without a generated file')
  assert.notEqual(await hashDesktopConfig(dir), first)
})

test('validSize accepts positive width-by-height sizes', () => {
  for (const size of ['1280x800', '800x600', '2560x1440', '99x99', '12800x8000']) {
    assert.equal(validSize(size), true, size)
  }
})

test('validSize rejects malformed, zero, and non-string sizes', () => {
  const rejected: unknown[] = [
    '', '0x800', '1280X800', '1280x', 'x800', '1280x0', '0x0', '-1280x800', '1280x-800',
    '1280x800x', '1280*800', '1280 x 800', ' 1280x800', '1280x800 ', 'abc', '1280.5x800',
    '123456x800', '1280x123456', '00000x800', '00012x00000', undefined, null,
  ]
  for (const size of rejected) assert.equal(validSize(size as unknown as string), false, String(size))
})

test('renderConfig and writeDesktopConfig reject an invalid size with USAGE', async (t) => {
  const dir = tempConfigDir(t)
  assert.throws(() => renderConfig({ size: '0x800', panicCommand: PANIC_COMMAND }), usageError)
  await assert.rejects(
    writeDesktopConfig({ configDir: dir, size: '1280X800', panicCommand: PANIC_COMMAND }),
    usageError,
  )
  assert.ok(!existsSync(join(dir, 'hypr')))
})
